"""Daily team briefs: one original write-up per team per day, kept permanently.

Generated by jobs/daily_briefs.py (scheduled), read by the site and the tweet bot.
"""
import json
import os
from datetime import datetime, timezone
from zoneinfo import ZoneInfo

from lib import store
from lib.articles import collect_ranked_articles
from lib.espn import facts_text, team_snapshot
from lib.factcheck import check
from lib.published import parse_date, published_many
from lib.search import tavily_search
from lib.teams import TEAMS, TEAM_SLUGS
from utils.article_filter import get_source_name_from_url

EASTERN = ZoneInfo("America/New_York")
_MAX_SOURCES = 16
_MAX_AGE_HOURS = 96


def local_today() -> str:
    """Today's date in Philadelphia, YYYY-MM-DD."""
    return datetime.now(EASTERN).date().isoformat()


def _date_score(day: str) -> int:
    return int(day.replace("-", ""))


# ---------------------------------------------------------------------------
# Storage
# ---------------------------------------------------------------------------

def save_brief(brief: dict) -> None:
    r = store.client()
    team, day = brief["team"], brief["date"]
    r.set(store.key("brief", team, day), json.dumps(brief))
    r.zadd(store.key("briefs", team), {day: _date_score(day)})
    r.zadd(store.key("briefs", "all"), {f"{team}:{day}": _date_score(day)})


def get_brief(team: str, day: str) -> dict | None:
    raw = store.client().get(store.key("brief", team, day))
    return json.loads(raw) if raw else None


def brief_dates(team: str, limit: int = -1) -> list[str]:
    """Dates with a brief for this team, newest first."""
    end = -1 if limit < 0 else limit - 1
    return list(store.client().zrevrange(store.key("briefs", team), 0, end))


def latest_brief(team: str) -> dict | None:
    dates = brief_dates(team, limit=1)
    return get_brief(team, dates[0]) if dates else None


def recent_briefs(limit: int = 40) -> list[tuple[str, str]]:
    """(team, date) pairs across all teams, newest first."""
    members = store.client().zrevrange(store.key("briefs", "all"), 0, limit - 1)
    return [tuple(m.split(":", 1)) for m in members]


# ---------------------------------------------------------------------------
# Generation
# ---------------------------------------------------------------------------

def _gather_sources(team: str, query: str | None = None) -> list[dict]:
    """Articles from our scrapers plus a fresh news search, newest first. Anything older than
    _MAX_AGE_HOURS is dropped; undated articles are kept after the dated ones."""
    t = TEAMS[team]
    sources = []
    seen = set()
    for a in collect_ranked_articles(team, max_articles=15):
        if a["title"] and a["url"] not in seen:
            seen.add(a["url"])
            sources.append({"title": a["title"], "url": a["url"], "source": a["source"],
                            "snippet": a["description"][:300], "published": None})
    for r in tavily_search(query or f"{t['full_name']} news", topic="news", max_results=10, time_range="day"):
        url = (r.get("url") or "").strip()
        title = (r.get("title") or "").strip()
        if url.startswith("http") and title and url not in seen:
            seen.add(url)
            sources.append({"title": title, "url": url, "source": get_source_name_from_url(url),
                            "snippet": (r.get("content") or "")[:300].strip(),
                            "published": parse_date(r.get("published_date"))})
    dates = published_many([s["url"] for s in sources if not s["published"]])
    now = datetime.now(timezone.utc)
    for s in sources:
        s["published"] = s["published"] or dates.get(s["url"])
    fresh = [s for s in sources if s["published"] and (now - s["published"]).total_seconds() < _MAX_AGE_HOURS * 3600]
    fresh.sort(key=lambda s: s["published"], reverse=True)
    undated = [s for s in sources if not s["published"]]
    return (fresh + undated)[:_MAX_SOURCES]


def _age_label(published: datetime | None) -> str:
    if not published:
        return "date unknown"
    hours = (datetime.now(timezone.utc) - published).total_seconds() / 3600
    when = published.astimezone(EASTERN).strftime("%a %b %-d, %-I:%M %p ET")
    return f"{when}, {hours:.0f}h ago" if hours < 48 else f"{when}, {hours / 24:.0f} days ago"


_SYSTEM = """You are the editor of Philly Sport Daily, writing the daily {team} brief for Philadelphia fans.

Write an original brief that tells a fan what matters today and why, using ONLY the numbered sources and ESPN facts provided.
- Freshness: lead with what happened in the last 24 hours (each source shows when it was published). Anything older is
  background: call it "earlier this week" (or similar) and never present it as today's news. If ESPN shows a game in the
  last day, the result leads, using ESPN's score and stat leaders exactly. ESPN facts are data only: never attribute an
  opinion or analysis to ESPN unless it comes from an ESPN article in the sources.
- Don't repeat a recent brief's lead (listed below) unless there is a genuinely new development; if so, say what changed.
- Synthesize: group related stories into 2 to 4 sections, explain the stakes, connect storylines. Do not just list headlines.
- Never invent facts, scores, stats, quotes, injuries, trades or dates. If a detail is not in the sources, leave it out.
- Attribute notable claims to the outlet (e.g. "per PhillyVoice"). Rumors must be labeled as rumors.
- Voice: knowledgeable local fan who respects the reader. Plain, specific, a little personality. No hype words, no em dashes, no "it's not just X, it's Y".
- Total length 250 to 450 words. If the news is thin, write less rather than padding.
- Today's date is {today}. Do not describe the season phase unless the sources do.

Return JSON with exactly these keys:
{{"headline": "specific, under 90 characters, no clickbait",
  "summary": "2 to 3 sentences, the most important takeaways",
  "sections": [{{"heading": "short", "body": "1 to 3 paragraphs separated by blank lines", "sources": [source numbers used]}}]}}"""


def _recent_leads(team: str, before: str) -> str:
    lines = []
    for d in brief_dates(team, limit=4):
        if d < before and (b := get_brief(team, d)):
            lines.append(f"- {d}: {b['headline']}")
    return "Recent briefs (don't repeat these leads without new developments):\n" + "\n".join(lines[:3]) if lines else ""


def generate_brief(team: str, day: str | None = None, postgame: bool = False) -> dict | None:
    """Write today's brief for a team. Returns the brief dict, or None if there's nothing to write about.
    postgame=True searches for game recaps so the brief leads with the result."""
    from openai import OpenAI

    day = day or local_today()
    snapshot = team_snapshot(team)
    query = None
    if postgame and (g := snapshot.get("last_game")):
        query = f"{TEAMS[team]['full_name']} {g['opponent']} game recap"
    sources = _gather_sources(team, query)
    if len(sources) < 3:
        print(f"{team}: only {len(sources)} sources, skipping brief")
        return None

    numbered = "\n\n".join(
        f"[{i}] {s['title']} ({s['source']}; published {_age_label(s['published'])})\n{s['snippet']}"
        for i, s in enumerate(sources, 1)
    )
    context = "\n\n".join(x for x in (facts_text(snapshot), _recent_leads(team, day)) if x)
    model = os.environ.get("BRIEF_MODEL", "gpt-5.4-mini")
    resp = OpenAI().chat.completions.create(
        model=model,
        response_format={"type": "json_object"},
        messages=[
            {"role": "system", "content": _SYSTEM.format(team=TEAMS[team]["full_name"], today=day)},
            {"role": "user", "content": f"{context}\n\nSources:\n\n{numbered}"},
        ],
    )
    data = json.loads(resp.choices[0].message.content or "{}")

    sections = []
    used = []
    for sec in data.get("sections") or []:
        body = (sec.get("body") or "").strip()
        if not body:
            continue
        refs = []
        for n in sec.get("sources") or []:
            if isinstance(n, int) and 1 <= n <= len(sources):
                s = sources[n - 1]
                ref = {"title": s["title"], "url": s["url"], "source": s["source"]}
                refs.append(ref)
                if ref not in used:
                    used.append(ref)
        sections.append({
            "heading": (sec.get("heading") or "").strip(),
            "paragraphs": [p.strip() for p in body.split("\n\n") if p.strip()],
            "sources": refs,
        })
    headline = (data.get("headline") or "").strip()
    summary = (data.get("summary") or "").strip()
    if not headline or not summary or not sections:
        print(f"{team}: model returned an incomplete brief, skipping")
        return None

    paragraphs = [(si, pi) for si, sec in enumerate(sections) for pi in range(len(sec["paragraphs"]))]
    items = [headline, summary] + [sections[si]["paragraphs"][pi] for si, pi in paragraphs]
    fixes = check(items, f"{context}\n\nSources:\n\n{numbered}")
    headline = fixes.get(0) or headline
    summary = fixes.get(1) or summary
    for k, (si, pi) in enumerate(paragraphs, 2):
        if k in fixes:
            sections[si]["paragraphs"][pi] = fixes[k]
    for sec in sections:
        sec["paragraphs"] = [p for p in sec["paragraphs"] if p]
    sections = [sec for sec in sections if sec["paragraphs"]]

    return {
        "team": team,
        "date": day,
        "headline": headline,
        "summary": summary,
        "sections": sections,
        "sources": used,
        "generated_at": datetime.now(EASTERN).isoformat(timespec="minutes"),
        "model": model,
    }


def generate_all(day: str | None = None) -> list[dict]:
    day = day or local_today()
    written = []
    for team in TEAM_SLUGS:
        try:
            brief = generate_brief(team, day)
        except Exception as e:
            print(f"{team}: brief generation failed: {e}")
            continue
        if brief:
            save_brief(brief)
            written.append(brief)
            print(f"{team}: saved brief '{brief['headline']}'")
    return written
